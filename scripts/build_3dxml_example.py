#!/usr/bin/env python3
"""Fetch the unpacked 3D XML sample from i2e-haw-hamburg/cad-in-unity (Apache-2.0), zip it into
a real .3dxml (a ZIP whose Manifest.xml names the root product structure file), and write
public/examples/3dxml/quad.3dxml, its license text and data/examples/3dxml.yaml (size, sha256,
license, provenance). The zip is deterministic (fixed timestamps, fixed order), so a rerun gives
the same checksum. Policy: docs/decisions/0005-format-examples.md.

Run from the repo root:  python3 scripts/build_3dxml_example.py [download dir]
"""
import hashlib
import os
import subprocess
import sys
import zipfile

import yaml

ROOT = os.getcwd()
TODAY = os.environ.get("EXAMPLES_DATE", "2026-11-22")
REPO = "i2e-haw-hamburg/cad-in-unity"
FOLDER = "3D XML Example"
RAW = "https://raw.githubusercontent.com/%s/master/" % REPO
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.getcwd(), ".cache", "3dxml-src")

# The folder as published. Manifest.xml names the root "Quad.3dxml" and the material links point
# at urn:3DXML:Quad.3dxml, so the root goes into the archive under that name (the repository
# stores it as quad.3dxml). .IntegrityCertificat is left out: it is a checksum CATIA writes for
# the archive it made, and this archive is a new one.
ROOT_FILE = ("quad.3dxml", "Quad.3dxml")
PARTS = [
    "Axle.3DRep", "Chassis.3DRep", "NonAscii_208.3DRep", "Wheel.3DRep",
    "CATMaterialRef.3dxml", "CATRepImage.3dxml",
    "Chroma_Material_Library_CATMaterial1_2_Rendering.3DRep",
    "Dashboard_Material_Library_CATMaterial1_3_Rendering.3DRep",
    "Fire_Red_Material_Library_CATMaterial1_Rendering.3DRep",
    "Gold_Metal_Material_Library_CATMaterial1_1_Rendering.3DRep",
    "material_12_Rendering.3DRep", "concrete.jpg", "dashboard.jpg", "Preview2D.png",
]


def curl(url, dest):
    subprocess.run(["curl", "-fsSL", "-A", "engineering-map", "-o", dest, url], check=True)


os.makedirs(SRC, exist_ok=True)
for name in ["Manifest.xml", ROOT_FILE[0], *PARTS]:
    curl(RAW + (FOLDER + "/" + name).replace(" ", "%20"), os.path.join(SRC, name))
curl(RAW + "LICENSE", os.path.join(SRC, "LICENSE"))

out_dir = os.path.join(ROOT, "public", "examples", "3dxml")
os.makedirs(out_dir, exist_ok=True)
out = os.path.join(out_dir, "quad.3dxml")
with zipfile.ZipFile(out, "w") as z:
    for src_name, arc_name in [("Manifest.xml", "Manifest.xml"), ROOT_FILE, *[(p, p) for p in PARTS]]:
        info = zipfile.ZipInfo(arc_name, date_time=(2009, 5, 20, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o644 << 16
        with open(os.path.join(SRC, src_name), "rb") as fh:
            z.writestr(info, fh.read(), compresslevel=9)

with open(os.path.join(SRC, "LICENSE"), "rb") as fh:
    lic = fh.read()
with open(os.path.join(out_dir, "quad.3dxml.LICENSE.txt"), "wb") as fh:
    fh.write(("License of quad.3dxml (Apache-2.0), from https://github.com/%s\n\n" % REPO).encode() + lic)

data = open(out, "rb").read()
entry = {
    "format": "3dxml",
    "file": "examples/3dxml/quad.3dxml",
    "contains": "A small four-wheeled car named Quad, as 3D XML 4.3 from CATIA V5: the product structure "
                "(chassis, axle assemblies, wheels, steering wheel, placed by matrices), tessellated .3DRep meshes "
                "with levels of detail, materials and a 2D preview.",
    "origin": "third-party",
    "license": "Apache-2.0",
    "attribution": "%s contributors, folder \"%s\". License text: quad.3dxml.LICENSE.txt." % (REPO, FOLDER),
    "source_url": "https://github.com/%s/tree/master/3D%%20XML%%20Example" % REPO,
    "size": len(data),
    "sha256": hashlib.sha256(data).hexdigest(),
    "as_of": TODAY,
    "note": "Zipped for this site from the unpacked folder, as a .3dxml is. The file says Generator "
            "CATIA V5 and may be a re-posted Dassault sample; the repository licence (Apache-2.0) "
            "alone does not prove the sample itself is freely licensed.",
}
with open(os.path.join(ROOT, "data", "examples", "3dxml.yaml"), "w") as fh:
    fh.write("# Generated by scripts/build_3dxml_example.py. Third-party sample zipped into a .3dxml.\n")
    yaml.safe_dump({"examples": [entry]}, fh, sort_keys=False, width=100)
print("%s %d bytes %s" % (out, len(data), entry["sha256"]))
